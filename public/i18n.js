 function localizePlayerLabel(v){
   let s=String(v??"");
   s=s.replace(/ — Красный$/," — Кыһыл")
      .replace(/ — Чёрный$/," — Хара")
      .replace(/ — Синий$/," — Күөх")
      .replace(/ — Бело-синий$/," — Үрүҥ-күөх");
   return s==="Игрок"?"Оонньооччу":s;
 }

 function localize(value){
   const s=String(value??"");
   if(lang()!=="sah")return s;
   if(Object.prototype.hasOwnProperty.call(exactSah,s))return exactSah[s];
   const dyn=dynamicSah(s);
   if(dyn!==s)return dyn;
   return localizePlayerLabel(s);
 }

